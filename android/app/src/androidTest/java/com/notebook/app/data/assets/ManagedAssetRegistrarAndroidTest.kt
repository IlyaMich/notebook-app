package com.notebook.app.data.assets

import android.content.Context
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.notebook.app.data.local.AppDatabase
import com.notebook.app.data.local.AppDatabaseProvider
import com.notebook.app.data.local.entity.AssetEntity
import java.io.ByteArrayInputStream
import java.io.File
import java.io.IOException
import java.util.UUID
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/** Only uses a unique disposable test directory and an isolated on-disk Room DB. */
@RunWith(AndroidJUnit4::class)
class ManagedAssetRegistrarAndroidTest {
    private lateinit var context: Context
    private lateinit var databaseName: String
    private lateinit var root: File
    private var db: AppDatabase? = null

    private val png = byteArrayOf(
        0x89.toByte(), 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
        0x00, 0x00, 0x00, 0x00,
    )

    @Before fun setUp() {
        context = InstrumentationRegistry.getInstrumentation().targetContext
        val id = UUID.randomUUID().toString()
        databaseName = "sto04-registrar-$id.sqlite"
        root = File(context.filesDir, "sto04-registrar-$id")
        assertTrue("Unable to create isolated test root", root.mkdir())
        db = AppDatabaseProvider.openIsolated(context, databaseName)
    }

    @After fun tearDown() {
        db?.close()
        context.deleteDatabase(databaseName)
        // This path was freshly generated by this test and cannot contain live app assets.
        if (::root.isInitialized && root.name.startsWith("sto04-registrar-")) {
            root.deleteRecursively()
        }
    }

    @Test fun registrationSurvivesRoomCloseAndReopenAndDuplicateKeepsId() = runBlocking {
        val initialDb = requireNotNull(db)
        val first = ManagedAssetRegistrar(ManagedAssetFileStore(root), initialDb.assetDao())
            .register(ByteArrayInputStream(png), "image/png")
        assertEquals("finalized", first.state)
        assertArrayEquals(png, File(root, first.relativePath).readBytes())
        assertEquals(first, initialDb.assetDao().findBySha256(first.sha256))
        initialDb.close()
        db = null
        val reopened = AppDatabaseProvider.openIsolated(context, databaseName)
        db = reopened
        val duplicate = ManagedAssetRegistrar(ManagedAssetFileStore(root), reopened.assetDao())
            .register(ByteArrayInputStream(png), "image/png")
        assertEquals(first, duplicate)
        assertEquals(1, reopened.assetDao().countAll())
    }

    @Test fun incompatibleExistingRoomMetadataFailsClosedWithoutDeletingFile() = runBlocking {
        val localDb = requireNotNull(db)
        val stored = ManagedAssetFileStore(root).stageAndFinalize(ByteArrayInputStream(png), "image/png")
        val conflicting = AssetEntity(
            id = UUID.randomUUID().toString(),
            sha256 = stored.sha256,
            mimeType = stored.mimeType,
            byteSize = stored.byteSize,
            relativePath = stored.relativePath,
            state = "quarantined",
        )
        localDb.assetDao().insert(conflicting)
        val failure = runCatching {
            ManagedAssetRegistrar(ManagedAssetFileStore(root), localDb.assetDao())
                .register(ByteArrayInputStream(png), "image/png")
        }.exceptionOrNull()
        assertTrue("Conflicting state must not be reported as finalized", failure is IOException)
        assertEquals(conflicting, localDb.assetDao().findBySha256(stored.sha256))
        assertArrayEquals(png, File(root, stored.relativePath).readBytes())
    }
}
